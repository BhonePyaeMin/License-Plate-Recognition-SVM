function ops = prefilterOps()
%PREFILTEROPS  Table of the pre-filters offered by the filter panel of the GUI (and APPLYPREFILTERS).
%   ops = PREFILTEROPS() returns a struct array with the fields
%     group   topic of the image-processing course the filter belongs to
%     name    text shown in the drop-down list
%     params  struct array (label, min, max, default, tip) of up to 2 numbers
%     help    two or three sentences: what the filter does, where it helps, where it hurts
%     run     function handle  [J, info] = run(I, p, pad, kernel)
%             I input image (double, gray or RGB), p vector with the parameter values,
%             pad border handling 'replicate' | 'symmetric' | 'zero' (EDGE EFFECT AND PADDING of every
%             spatial filter: how pixels outside the picture are filled in), kernel numeric matrix used by
%             the convolution filter. J result in [0,1], info one-line description.
%   Why pre-filters at all: the plate SVM and the character SVM were trained on reasonably sharp, well
%   exposed pictures. Noise, blur, low contrast or uneven light move a photo away from that; a suitable
%   filter moves it back. A wrong filter does harm (a Gaussian blur removes the stroke edges of small
%   characters), so check the result with "Recognise on filtered photo" or "Compare".

L = {};
par = @(label, lo, hi, def, tip) struct('label', label, 'min', lo, 'max', hi, 'default', def, 'tip', tip);
none = struct('label', {}, 'min', {}, 'max', {}, 'default', {}, 'tip', {});
odd = @(x) 2 * floor(round(x) / 2) + 1;

% ---------------------------------- spatial resolution -------------------------------------
methods = {'nearest', 'bilinear', 'bicubic'};
L{end+1} = mk('Spatial resolution', 'Resize (change the resolution)', ...
    [par('Scale', 0.25, 4, 1.5, 'Factor for width and height: 2 doubles the picture, 0.5 halves it'), ...
     par('Interp. 1-3', 1, 3, 3, 'Interpolation: 1 nearest neighbour, 2 bilinear, 3 bicubic')], ...
    @(I,p,pad,K) deal(imResize(I, p(1), methods{min(3, max(1, round(p(2))))}), ...
        sprintf('scale %.2f, %s interpolation (the picture gets %d x %d pixels)', p(1), methods{min(3, max(1, round(p(2))))}, max(1, round(size(I,2) * p(1))), max(1, round(size(I,1) * p(1))))), ...
    ['Changes the number of pixels. Enlarge (2, bicubic) a small or far plate so that the strokes of the characters get smoother edges; ' ...
     'it cannot add detail that the camera did not record. Never shrink a photo to save time: it cost 3 of 16 plates.']);

% ----------------------------- spatial filtering: convolution -----------------------------------
L{end+1} = mk('Spatial filtering (convolution)', 'Convolution with my own kernel', none, ...
    @(I,p,pad,K) deal(spatialFilter(I, K, pad), sprintf('%d x %d kernel, sum %.3g, %s padding', size(K, 1), size(K, 2), sum(K(:)), pad)), ...
    ['Slides the matrix typed under "Own kernel" over the photo (pick Sharpen, Laplacian, box, Gaussian or Sobel as a start). ' ...
     'Sharpen keeps the photo readable (7 of 16 test plates); the edge presets (Laplacian, Sobel: the numbers add up to 0) turn the photo into an edge map, which the plate search cannot use.']);

% ------------------------------------- linear smoothing -----------------------------------------
L{end+1} = mk('Linear smoothing filters', 'Mean (box) filter', par('Window', 3, 15, 3, 'Window size in pixels (odd)'), ...
    @(I,p,pad,K) deal(spatialFilter(I, ones(odd(p(1))) / odd(p(1))^2, pad), sprintf('%d x %d box average, %s padding', odd(p(1)), odd(p(1)), pad)), ...
    ['Replaces every pixel by the average of its neighbours: noise gets weaker but the edges of the characters get blurred too. ' ...
     'Usually does harm on plates; use only a small window (3) on very grainy photos.']);
L{end+1} = mk('Linear smoothing filters', 'Gaussian filter', [par('Window', 3, 21, 3, 'Window size in pixels (odd)'), par('Sigma', 0.5, 6, 0.8, 'Width of the Gaussian in pixels')], ...
    @(I,p,pad,K) deal(spatialFilter(I, gaussianKernel(odd(p(1)), p(2)), pad), sprintf('%d x %d Gaussian, sigma %.2f, %s padding', odd(p(1)), odd(p(1)), p(2), pad)), ...
    ['Smooth blur with a bell-shaped weight. Removes fine noise but also the thin strokes of small characters: ' ...
     'a 5 x 5, sigma 1 Gaussian on the clean test photos cost 4 of 16 plates (8 -> 4), so the start values are the mild 3 x 3, sigma 0.8 (7 of 16). Use it only when nothing else is available.']);

% ----------------------------- non-linear filters (noise) ---------------------------------------
L{end+1} = mk('Non-linear filters (noise)', 'Median filter', par('Window', 3, 9, 3, 'Window size in pixels (odd)'), ...
    @(I,p,pad,K) deal(medianFilter(I, odd(p(1)), pad), sprintf('%d x %d median, %s padding (best against salt-and-pepper noise)', odd(p(1)), odd(p(1)), pad)), ...
    ['Replaces every pixel by the median of its neighbours. Removes isolated white or black dots and keeps edges (3 for few dots, 5 for many). ' ...
     'Do not use it on ordinary grain: it rounds off thin strokes.']);
L{end+1} = mk('Non-linear filters (noise)', 'Bilateral filter (edge-preserving)', [par('Spatial sigma', 0.5, 2, 1.5, 'Distance weight in pixels'), par('Range sigma', 0.05, 0.4, 0.15, 'Grey-level weight; relative to the grey range of the photo')], ...
    @(I,p,pad,K) deal(bilateralFilter(I, p(1), p(2), pad), sprintf('sigma_s %.2f px, sigma_r %.2f: smooths noise, keeps character edges', p(1), p(2))), ...
    ['Averages only neighbours of similar brightness, so noise is smoothed but the character edges stay sharp. The best filter for grainy photos (Gaussian noise). ' ...
     'It did not help on dark night photos, and it is slow on big photos.']);

% -------------------------------------- sharpening / deblurring ---------------------------------
L{end+1} = mk('Sharpening and deblurring', 'Unsharp masking', [par('Amount', 0, 4, 1.5, 'How much of the detail is added back'), par('Blur sigma', 0.5, 5, 1.5, 'Size of the detail, in pixels')], ...
    @(I,p,pad,K) deal(I + p(1) * (I - spatialFilter(I, gaussianKernel(2 * ceil(3 * p(2)) + 1, p(2)), pad)), sprintf('I + %.2f*(I - Gaussian(I)), sigma %.2f', p(1), p(2))), ...
    ['Makes edges steeper (adds back the difference between the photo and a blurred copy). Helps a little with soft or enlarged photos. ' ...
     'High amounts amplify noise and draw halos next to the edges; keep the amount at 1 to 1.5.']);
L{end+1} = mk('Sharpening and deblurring', 'Laplacian sharpening', par('Amount', 0, 3, 1, 'Strength of the sharpening'), ...
    @(I,p,pad,K) deal(I - p(1) * spatialFilter(I, [1 1 1; 1 -8 1; 1 1 1], pad), sprintf('I - %.2f*Laplacian(I), 8-neighbour kernel', p(1))), ...
    ['Subtracts the Laplacian (second derivative) from the photo: a stronger sharpening than unsharp masking that also boosts noise. ' ...
     'At the start value 1 it read 7 of 16 test plates with fewer correct characters (63.1 % instead of 74.6 %): try 0.5 first.']);
L{end+1} = mk('Sharpening and deblurring', 'Deblur (Richardson-Lucy)', [par('Blur sigma', 0.5, 4, 1.5, 'Width of the blur to undo, in pixels'), par('Iterations', 3, 30, 10, 'More iterations amplify noise')], ...
    @(I,p,pad,K) deal(deblurRL(I, p(1), p(2)), sprintf('Gaussian PSF sigma %.2f, %d iterations (too many amplify noise)', p(1), round(p(2)))), ...
    ['Tries to undo an out-of-focus (Gaussian) blur. On blurred test photos the gain was nil and on clean photos it read 10 of 16 plates but with fewer correct characters: not reliable; ' ...
     'it does not repair motion blur. Take the photo again if you can.']);

% ------------------------------------ brightness and contrast -----------------------------------
L{end+1} = mk('Brightness and contrast', 'Gamma correction', par('Gamma', 0.3, 3, 0.7, 'Below 1 brightens, above 1 darkens'), ...
    @(I,p,pad,K) deal(grayTransform(I, 'gamma', p(1)), sprintf('J = I^%.2f', p(1))), ...
    ['Brightens (below 1) or darkens (above 1) the middle tones. The program already repairs the brightness of dark or bright photos itself, ' ...
     'so gamma rarely adds anything; 0.6 is the safest try for a dark photo.']);
L{end+1} = mk('Brightness and contrast', 'Brightness / contrast', [par('Contrast', 0.3, 3, 1.4, 'Gain around grey 0.5'), par('Brightness', -0.3, 0.3, 0, 'Added to every pixel')], ...
    @(I,p,pad,K) deal(grayTransform(I, 'linear', p(1), p(2)), sprintf('J = %.2f*(I-0.5)+0.5%+.2f', p(1), p(2))), ...
    ['Linear change: gain around grey 0.5 plus an offset. Pixels pushed beyond black or white are cut off and lost, so do not overdo it.']);
L{end+1} = mk('Brightness and contrast', 'Contrast stretching', [par('Low %', 0, 20, 1, 'Percentile of the photo that becomes black'), par('High %', 80, 100, 99, 'Percentile of the photo that becomes white')], ...
    @(I,p,pad,K) deal(grayTransform(I, 'stretch', p(1), p(2)), sprintf('stretch %.0f%%..%.0f%% to 0..1', p(1), p(2))), ...
    ['Stretches the chosen grey range to full black and white. For hazy, foggy or washed-out photos. ' ...
     'The program stretches very flat photos itself, so the gain is small.']);
L{end+1} = mk('Brightness and contrast', 'Histogram equalisation', none, ...
    @(I,p,pad,K) deal(histEqualize(I), 'global histogram flattened (V channel for colour)'), ...
    ['Flattens the grey-level histogram of the whole photo. Brings out detail in a flat photo but also lifts noise and over-exposes the bright areas. ' ...
     'The local version (CLAHE) is usually the better choice.']);
L{end+1} = mk('Brightness and contrast', 'Local histogram equalisation (CLAHE)', [par('Tiles', 2, 16, 8, 'Tiles per side of the picture'), par('Clip limit', 1, 10, 3, 'Limits the contrast boost, which limits noise')], ...
    @(I,p,pad,K) deal(localHistEqualize(I, p(1), p(2)), sprintf('%d x %d tiles, clip limit %.1f', round(p(1)), round(p(1)), p(2))), ...
    ['Equalises the histogram tile by tile, with a limit on the boost. Brings out the plate when one side of a normal-brightness photo is in shadow. ' ...
     'On dark photos it amplifies the noise and cost plates; lower the clip limit (1.5 to 2) if you try it.']);

% -------------------------------------------- illumination -------------------------------------
L{end+1} = mk('Uneven illumination', 'Illumination correction', [par('Blur sigma', 10, 100, 40, 'Size of the light estimate, per 1000 px of photo width'), par('Strength', 0, 1, 1, '0 = no change, 1 = full correction')], ...
    @(I,p,pad,K) deal(illuminationCorrect(I, p(1), p(2)), sprintf('divided by a wide Gaussian estimate of the light, strength %.2f', p(2))), ...
    ['Estimates the slowly changing light and divides it out, so a shadow across the plate is levelled. ' ...
     'Needs a plate that is smaller than the shadow; it cannot restore burnt-out or pitch-black areas.']);

% ------------------------------------------- frequency domain -----------------------------------
L{end+1} = mk('Frequency domain', 'Frequency low-pass (noise)', par('Cut-off', 0.05, 0.8, 0.5, 'Fraction of the highest frequency that is kept'), ...
    @(I,p,pad,K) deal(freqFilter(I, 'lowpass', p(1), 'butterworth'), sprintf('FFT Butterworth low-pass, cut-off %.2f', p(1))), ...
    ['Keeps only the slow changes of the photo (Fourier domain). Removes the pixel grid and colour fringes of a photographed screen and very fine noise. ' ...
     'Every cut-off blurs the characters a little: on the clean test photos 0.3 cost 4 of 16 plates, 0.5 (the start value) 1 plate.']);
L{end+1} = mk('Frequency domain', 'Frequency band-pass', [par('Low cut-off', 0.01, 0.3, 0.01, 'Slow changes (shading) below this are removed'), par('High cut-off', 0.2, 0.9, 0.8, 'Fine changes (noise) above this are removed')], ...
    @(I,p,pad,K) deal(freqFilter(I, 'bandpass', [p(1) p(2)], 'gaussian'), 'FFT Gaussian band-pass (removes slow shading and fine noise)'), ...
    ['Keeps the middle frequencies: removes slow shading and fine noise at the same time. ' ...
     'A high cut-off removes the fine detail of the characters: with 0.5 it read only 3 of 16 test plates, so the start values are 0.01 and 0.8 (9 of 16, about as good as doing nothing).']);

ops = [L{:}];

    function o = mk(group, name, params, run, help)
        o = struct('group', group, 'name', name, 'params', params, 'help', help, 'run', @(I, p, pad, K) finish(run, I, p, pad, K));
    end
end

function [J, info] = finish(run, I, p, pad, K)
% run the filter on a double image and clip the result to [0,1]
I = toDouble(I);
if nargin < 5 || isempty(K), K = 1; end
[J, info] = run(I, p, pad, K);
J = min(max(J, 0), 1);
end

function J = medianFilter(I, k, pad)
% k x k median with the chosen border handling
r = (k - 1) / 2;
[h, w, nc] = size(I);
P = padImage(I, r, r, pad);
J = zeros(h, w, nc);
for ch = 1:nc
    S = zeros(h, w, k * k);
    n = 0;
    for dy = 0:k-1
        for dx = 0:k-1
            n = n + 1;
            S(:,:,n) = P(dy + (1:h), dx + (1:w), ch);
        end
    end
    J(:,:,ch) = median(S, 3);
end
end
